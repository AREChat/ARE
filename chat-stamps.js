const STAMP_LIST = ["👍","🙏","🎉","❤️","😂","😭","😡","🤔","👏","💪","🍻","✨"];

const EMOJI_FREQ_KEY = "are_emoji_freq_v1";
function emojiFreqLoad(){
    try{ return JSON.parse(localStorage.getItem(EMOJI_FREQ_KEY) || "{}") || {}; }catch(_e){ return {}; }
}
function emojiFreqBump(emoji){
    try{
        const map = emojiFreqLoad();
        map[emoji] = (map[emoji] || 0) + 1;
        localStorage.setItem(EMOJI_FREQ_KEY,JSON.stringify(map));
    }catch(_e){ /* 保存できなくても続行 */ }
}
function emojiFreqTop(n){
    const map = emojiFreqLoad();
    return Object.keys(map).sort((a,b) => map[b] - map[a]).slice(0,n);
}

function initStamps(){
    const panel = document.createElement("div");
    panel.id = "emojiPanel";
    panel.className = "emoji-panel";
    panel.hidden = true;
    panel.innerHTML = '<div class="emoji-tabs"><button type="button" class="button-secondary" data-ep="emoji">絵文字（入力欄に入れる）</button><button type="button" class="button-secondary" data-ep="stamp">スタンプ（すぐ送る）</button><button type="button" class="button-secondary" data-ep="close">閉じる</button></div>' +
        '<div class="emoji-search-row" id="emojiSearchRow" hidden><input type="search" id="emojiSearch" class="emoji-search" placeholder="🔍 絵文字を検索"></div>' +
        '<div class="emoji-grid" id="emojiGrid"></div>' +
        '<div class="emoji-cattabs" id="emojiCatTabs" hidden></div>';
    document.querySelector(".composer .composer-bottom").insertAdjacentElement("beforebegin",panel);
    feat.emojiMode = "emoji";
    feat.emojiCat = EMOJI_CATS[0].key;
    feat.emojiQuery = "";
    paintEmojiGrid();
    panel.addEventListener("click",onEmojiClick);
    panel.addEventListener("input",(event) => {
        if(event.target.id !== "emojiSearch") return;
        feat.emojiQuery = event.target.value.trim();
        paintEmojiGrid(true);
    });
    document.getElementById("emojiButton").addEventListener("click",() => { panel.hidden = !panel.hidden; });
}

function emojiSearchResults(query){
    const q = query.toLocaleLowerCase();
    const out = [];
    EMOJI_CATS.forEach((cat) => cat.list.forEach((row) => {
        if(row[0].includes(query) || (row[1] || "").toLocaleLowerCase().includes(q)) out.push(row[0]);
    }));
    return out;
}

function paintEmojiGrid(keepScroll){
    const grid = document.getElementById("emojiGrid");
    const searchRow = document.getElementById("emojiSearchRow");
    const catTabs = document.getElementById("emojiCatTabs");
    const stampMode = feat.emojiMode === "stamp";
    grid.className = "emoji-grid" + (stampMode ? " stamps" : "");
    searchRow.hidden = stampMode;
    catTabs.hidden = stampMode;

    if(stampMode){
        grid.innerHTML = STAMP_LIST.map((emoji) => '<button type="button" class="emoji-btn" data-emoji="' + escapeHtml(emoji) + '">' + escapeHtml(emoji) + '</button>').join("");
        return;
    }

    if(!keepScroll){
        const input = document.getElementById("emojiSearch");
        if(input) input.value = feat.emojiQuery || "";
    }
    catTabs.innerHTML = '<button type="button" class="emoji-cattab' + (feat.emojiCat === "recent" ? " on" : "") + '" data-ecat="recent" title="よく使う">🕐</button>' +
        EMOJI_CATS.map((cat) => '<button type="button" class="emoji-cattab' + (feat.emojiCat === cat.key ? " on" : "") + '" data-ecat="' + cat.key + '" title="' + escapeHtml(cat.label) + '">' + cat.icon + '</button>').join("");

    let html = "";
    const query = feat.emojiQuery || "";
    if(query){
        const found = emojiSearchResults(query);
        html = found.length
            ? found.map((emoji) => '<button type="button" class="emoji-btn" data-emoji="' + escapeHtml(emoji) + '">' + escapeHtml(emoji) + '</button>').join("")
            : '<div class="meta">見つかりませんでした。</div>';
    }else if(feat.emojiCat === "recent"){
        const top = emojiFreqTop(40);
        html = top.length
            ? top.map((emoji) => '<button type="button" class="emoji-btn" data-emoji="' + escapeHtml(emoji) + '">' + escapeHtml(emoji) + '</button>').join("")
            : '<div class="meta">まだ「よく使う」はありません。絵文字を選ぶと、ここに出てきます。</div>';
    }else{
        const cat = EMOJI_CATS.find((c) => c.key === feat.emojiCat) || EMOJI_CATS[0];
        html = cat.list.map((row) => '<button type="button" class="emoji-btn" data-emoji="' + escapeHtml(row[0]) + '">' + escapeHtml(row[0]) + '</button>').join("");
    }
    grid.innerHTML = html;
}

async function onEmojiClick(event){
    const mode = event.target.closest("[data-ep]");
    if(mode){
        if(mode.dataset.ep === "close"){ document.getElementById("emojiPanel").hidden = true; return; }
        feat.emojiMode = mode.dataset.ep; paintEmojiGrid(); return;
    }
    const catBtn = event.target.closest("[data-ecat]");
    if(catBtn){
        feat.emojiCat = catBtn.dataset.ecat;
        feat.emojiQuery = "";
        paintEmojiGrid();
        return;
    }
    const pick = event.target.closest("[data-emoji]");
    if(!pick) return;
    emojiFreqBump(pick.dataset.emoji);
    if(feat.emojiMode === "stamp"){
        if(!state.currentRoom){ showToast("先にチャット相手を選択してください。"); return; }
        await sendMessagePayload({type:"text",text:pick.dataset.emoji,stamp:true},{keepInput:true});
        return;
    }
    const box = el.messageInput;
    if(box.disabled){ showToast("先にチャット相手を選択してください。"); return; }
    const start = box.selectionStart ?? box.value.length, end = box.selectionEnd ?? start;
    const next = box.value.slice(0,start) + pick.dataset.emoji + box.value.slice(end);
    if(Array.from(next).length > MAX_TEXT_LENGTH){ showToast("メッセージは4,000文字以内で入力してください。"); return; }
    box.value = next;
    const pos = start + pick.dataset.emoji.length;
    box.setSelectionRange(pos,pos);
    updateCharCount();
    box.focus();
}
